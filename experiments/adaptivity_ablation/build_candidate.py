"""Auditable transformation of the pinned Agent; only exploration is replaced."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

BEFORE = '''        # Keep pristine real beliefs separate from the fantasy planning ledger.
        real_env = env
        real_beliefs = deepcopy(beliefs)
        env = ScheduleEnvironment(initial_budget, initial_contacts, env.pilots_left,
                                  cells, beliefs, channels, reference_multiplier)
'''

AFTER = '''        # The complete schedule exists before the first real run_pilot call.
        schedule = deepcopy(env.schedule)
        planning_trace = self.last_trace["pilots"]
        self.last_trace["fixed_schedule"] = schedule
        self.last_trace["schedule_observations_are_fantasies"] = True
        self.last_trace["planning_diagnostics"] = planning_trace
        self.last_trace["pilots"] = []
        self.last_trace["resource_skips"] = []
        env, beliefs = real_env, real_beliefs
        by_offer = {(b.current, b.segment, b.target): b for b in beliefs}
        for index, planned in enumerate(schedule):
            if env.pilots_left <= 0 or env.remaining_contacts <= reserve_contacts:
                self.last_trace["resource_skips"].append({"index": index, "reason": "quota"})
                break
            action = dict(planned)
            unit_cost = float(channels[action["channel"]]["cost_per_contact"])
            available = int(env.remaining_contacts) - reserve_contacts
            if unit_cost > 0:
                spent = initial_budget - float(env.remaining_budget)
                available = min(available, int(max(0.0, min(env.remaining_budget,
                                                            pilot_budget - spent)) // unit_cost))
            action["n_customers"] = min(action["n_customers"], available)
            if action["n_customers"] < 10:
                self.last_trace["resource_skips"].append({"index": index, "reason": "resources"})
                continue
            belief = by_offer[action["filter_current_tariff"], action["filter_arpu_segment"],
                              action["target_tariff"]]
            multiplier = float(channels[action["channel"]]["conversion_multiplier"])
            result = env.run_pilot(**action)
            actual_n = int(result["n_customers"])
            observed = float(result["observed_lift_ratio"])
            if actual_n < 1 or not isfinite(observed):
                self.last_trace["warnings"].append("Non-finite or empty pilot response; no update from this observation")
                continue
            belief.observe(observed, actual_n, multiplier, reference_multiplier)
            mean, std = belief.posterior()
            planned_info = planning_trace[index]
            self.last_trace["pilots"].append({
                "current_tariff": belief.current, "arpu_segment": belief.segment,
                "target_tariff": belief.target, "channel": action["channel"],
                "n_customers": actual_n, "observed_lift_ratio": observed,
                "posterior_reference_mean": mean, "posterior_reference_std": std,
                "confirmation": planned_info["confirmation"],
                "estimated_information_value": planned_info["estimated_information_value"],
                "stratified_segment": planned_info["stratified_segment"],
                "schedule_index": index,
            })

'''


def build(source):
    source = source.replace("from math import isfinite, sqrt", "from copy import deepcopy\nfrom experiments.adaptivity_ablation.schedule import ScheduleEnvironment\nfrom math import isfinite, sqrt", 1)
    source = source.replace("class Agent:", "class FixedSurveyAgent:", 1)
    source = source.replace('Path(__file__).resolve().parent / "data"', 'Path(__file__).resolve().parents[2] / "data"', 1)
    start = "        for step in range(pilot_limit):\n"
    finish = "        options = make_options(profile, beliefs, channels, reference_multiplier, risk_weight=1.65)\n"
    assert source.count(start) == source.count(finish) == 1
    source = source.replace(start, BEFORE + start, 1).replace(finish, AFTER + finish, 1)
    return '# Generated by build_candidate.py from pinned main Agent; see protocol.md.\n' + source


if __name__ == "__main__":
    (ROOT / "experiments/adaptivity_ablation/fixed_agent.py").write_text(
        build((ROOT / "agent.py").read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
